        [MenuItem("Tartaria/Asset Replacement/Apply Spawner Updates")]
        public static void ApplySpawnerUpdates()
        {
            Debug.Log("[PrefabWireupGenerator] Applying spawner updates...");

            // Update Moon7ContentSpawner
            UpdateMoon7ContentSpawner();

            // Update Moon10ContentSpawner
            UpdateMoon10ContentSpawner();

            // Update BuildingSpawner
            UpdateBuildingSpawner();

            AssetDatabase.Refresh();
            Debug.Log("[PrefabWireupGenerator] ✓ All spawner scripts updated to use PrefabLibrary!");
        }

        static void UpdateMoon7ContentSpawner()
        {
            string path = ""Assets/_Project/Scripts/Integration/Moon7ContentSpawner.cs"";
            if (!File.Exists(path))
            {
                Debug.LogWarning($""[PrefabWireupGenerator] File not found: {path}"");
                return;
            }

            string content = File.ReadAllText(path);

            // Add using directive if not present
            if (!content.Contains(""using Tartaria.Integration;""))
            {
                content = content.Replace(""using Tartaria.World;"", 
                    ""using Tartaria.World;\nusing Tartaria.Integration;"");
            }

            // Replace Korath giant spawn
            content = Regex.Replace(content,
                @"_korathGiant = GameObject\.CreatePrimitive\(PrimitiveType\.Capsule\);\s*\n\s*_korathGiant\.name = ""Korath_Giant"";\s*\n\s*_korathGiant\.transform\.position = .*;",
                @"_korathGiant = PrefabLibrary.LoadKorath();
            _korathGiant.name = ""Korath_Giant"";
            _korathGiant.transform.position = stasisVaultCenter + Vector3.up * 5f;");

            // Replace Cassian spawn
            content = Regex.Replace(content,
                @"GameObject cassianObj = GameObject\.CreatePrimitive\(PrimitiveType\.Capsule\);",
                @"GameObject cassianObj = PrefabLibrary.LoadCassian();");

            // Replace mud golem spawn
            content = Regex.Replace(content,
                @"GameObject golemObj = GameObject\.CreatePrimitive\(PrimitiveType\.Capsule\);",
                @"GameObject golemObj = PrefabLibrary.LoadMudGolem();");

            File.WriteAllText(path, content);
            Debug.Log($""[PrefabWireupGenerator] ✓ Updated: {path}"");
        }

        static void UpdateMoon10ContentSpawner()
        {
            string path = ""Assets/_Project/Scripts/Integration/Moon10ContentSpawner.cs"";
            if (!File.Exists(path))
            {
                Debug.LogWarning($""[PrefabWireupGenerator] File not found: {path}"");
                return;
            }

            string content = File.ReadAllText(path);

            // Add using directive
            if (!content.Contains(""using Tartaria.Integration;""))
            {
                content = content.Replace(""using Tartaria.World;"", 
                    ""using Tartaria.World;\nusing Tartaria.Integration;"");
            }

            // Replace station building spawn
            content = Regex.Replace(content,
                @"var building = GameObject\.CreatePrimitive\(PrimitiveType\.Cube\);\s*\n\s*building\.name = ""StationBuilding"";\s*\n\s*building\.transform\.SetParent\(station\.transform\);\s*\n\s*building\.transform\.localScale = new Vector3\(30f, 10f, 30f\);",
                @"var building = PrefabLibrary.LoadRailwayStation();
            building.name = ""StationBuilding"";
            building.transform.SetParent(station.transform);");

            File.WriteAllText(path, content);
            Debug.Log($""[PrefabWireupGenerator] ✓ Updated: {path}"");
        }

        static void UpdateBuildingSpawner()
        {
            string path = ""Assets/_Project/Scripts/Integration/BuildingSpawner.cs"";
            if (!File.Exists(path))
            {
                Debug.LogWarning($""[PrefabWireupGenerator] File not found: {path}"");
                return;
            }

            string content = File.ReadAllText(path);

            // Add using directive
            if (!content.Contains(""using Tartaria.Integration;""))
            {
                content = content.Replace(""using Tartaria.World;"", 
                    ""using Tartaria.World;\nusing Tartaria.Integration;"");
            }

            // Add helper method to map building type to prefab
            string helperMethod = @"
        static GameObject LoadBuildingPrefab(string buildingType)
        {
            return buildingType switch
            {
                ""dome"" => PrefabLibrary.LoadBeauxArtsPavilion(),
                ""fountain"" => PrefabLibrary.LoadHarmonicFountain(),
                ""spire"" => PrefabLibrary.LoadBellTower(),
                _ => GameObject.CreatePrimitive(PrimitiveType.Cube)
            };
        }";

            // Insert helper method before LoadFallbackBuilding method
            if (!content.Contains(""LoadBuildingPrefab""))
            {
                content = content.Replace(
                    ""static GameObject LoadFallbackBuilding("",
                    helperMethod + ""\n\n        static GameObject LoadFallbackBuilding("");
            }

            // Replace primitive creation in LoadFallbackBuilding
            content = Regex.Replace(content,
                @"// Fallback: primitives\s*\n\s*var go = GameObject\.CreatePrimitive\(shape\);",
                @"// Try loading production prefab first
            var go = LoadBuildingPrefab(category);");

            File.WriteAllText(path, content);
            Debug.Log($""[PrefabWireupGenerator] ✓ Updated: {path}"");
        }
    }
